import MagicString from "magic-string";
import { analyzeModule } from "./context";
import { collectImportReplacements } from "./imports";
import { collectMacroReplacements } from "./render";

export type TransformCompdiMacrosResult = {
  code: string;
  map: ReturnType<MagicString["generateMap"]>;
};

export function transformCompdiMacros(
  code: string,
  id: string
): TransformCompdiMacrosResult | null {
  if (!/\.[cm]?[jt]sx?$/.test(id)) {
    return null;
  }

  if (
    !code.includes("@compdi/core") &&
    !code.includes('"compdi/macros"') &&
    !code.includes("'compdi/macros'") &&
    !code.includes('"compdi"') &&
    !code.includes("'compdi'")
  ) {
    return null;
  }

  const context = analyzeModule(code, id);
  if (!context) return null;

  const ms = new MagicString(code);
  if (!collectMacroReplacements(context, ms)) return null;

  // Only erase the import when there are actual macro calls to replace.
  // Without this guard, barrel re-export files (e.g. compdi/macros dist) would
  // have their import erased, leaving dangling export references.
  collectImportReplacements(context, ms);

  ms.prepend("// Generated by Compdi\n");

  return {
    code: ms.toString(),
    map: ms.generateMap({ hires: true, source: id, includeContent: true })
  };
}

